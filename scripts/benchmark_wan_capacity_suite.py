#!/usr/bin/env python3
"""Bounded, serial, conservative capacity ladder; never launches formal training."""
import argparse,json,os,subprocess,time,traceback
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--script',type=Path,required=True);p.add_argument('--baseline',type=Path,required=True);p.add_argument('--baseline-pid',type=int,required=True);p.add_argument('--model',type=Path,required=True);p.add_argument('--root',type=Path,required=True);p.add_argument('--logs',type=Path,required=True);a=p.parse_args()
a.root.mkdir(parents=True,exist_ok=True);a.logs.mkdir(parents=True,exist_ok=True)
summary={'status':'waiting_for_batch1','scope':'model-port capacity preflight, not full trainer/G3/reward throughput','formal_training_started':False,'candidates':[1,2,4,8],'reports':[],'skipped':[]};started=time.monotonic()
def save():
 q=a.root/'suite-summary.tmp';q.write_text(json.dumps(summary,indent=2));q.replace(a.root/'suite-summary.json')
def read_report(path):
 try:return json.loads(path.read_text())
 except (FileNotFoundError,json.JSONDecodeError):return None
def compact(d,path):
 return {**{k:v for k,v in d.items() if k!='gpu_samples'},'receipt':str(path)}
def quiet_gpu():
 for _ in range(60):
  text=subprocess.check_output(['nvidia-smi','--query-gpu=memory.used,memory.free,utilization.gpu','--format=csv,noheader,nounits'],text=True,timeout=10).strip()
  used,free,util=[float(v.strip()) for v in text.splitlines()[0].split(',')]
  if used<=4096 and util<=5 and free>=64000:return
  time.sleep(2)
 raise RuntimeError('Shared GPU is not at the quiet baseline; not touching other processes')
def predict_gib(d,new_batch):
 ratio=new_batch/d['batch'];estimates=[]
 for row in d['phases']:
  base=row.get('initial_allocated_gib',0.)
  if row['phase'].startswith('decode1-'):
   predicted=row['peak_allocated_gib']+.02*max(0,new_batch-d['batch'])
  else:predicted=base+max(0.,row['peak_allocated_gib']-base)*ratio
  reserve=max(0.,row['peak_reserved_gib']-row['peak_allocated_gib'])
  estimates.append(predicted*1.15+reserve+2.)
 return max(estimates)
try:
 save()
 while True:
  baseline=read_report(a.baseline/'report.json')
  if baseline and baseline['status']!='running':break
  if time.monotonic()-started>1800:raise TimeoutError('Baseline did not finish within bounded wait')
  time.sleep(5)
 if baseline['status']!='capacity_preflight_pass':raise RuntimeError('Baseline failed: '+str(baseline.get('error',baseline['status'])))
 for _ in range(60):
  try:os.kill(a.baseline_pid,0)
  except ProcessLookupError:break
  time.sleep(1)
 else:raise RuntimeError('Baseline process has not exited; refusing concurrent probe')
 summary['reports'].append(compact(baseline,a.baseline/'report.json'));summary['status']='running';save()
 cache=a.baseline/'conditioning-512.pt';assert cache.is_file(),'Need the real512 conditioning cache generated by baseline'
 previous=baseline
 for b in [2,4,8]:
  if time.monotonic()-started>7200:raise TimeoutError('Suite reached its two-hour bound')
  predicted=predict_gib(previous,b);budget=previous['allocator_budget_gib']
  if predicted>budget:
   summary['skipped'].append({'batch':b,'reason':'conservative forecast exceeds own-process safety budget; not an observed OOM','forecast_gib':predicted,'budget_gib':budget});save();continue
  quiet_gpu();out=a.root/f'batch{b}-r1'
  if out.exists():raise RuntimeError('Refusing to overwrite existing probe '+str(out))
  env=dict(os.environ,CUDA_VISIBLE_DEVICES='0',OMP_NUM_THREADS='2',TOKENIZERS_PARALLELISM='false')
  command=[os.sys.executable,'-u',str(a.script),'--model',str(a.model),'--conditioning-bundle',str(cache),'--batch',str(b),'--output',str(out),'--repeats','3']
  summary.update(active_batch=b,active_output=str(out),forecast_gib=predicted);save()
  with (a.logs/f'batch{b}-r1.log').open('w') as log:
   child=subprocess.Popen(command,env=env,stdout=log,stderr=subprocess.STDOUT);summary['child_pid']=child.pid;save()
   try:rc=child.wait(timeout=1800)
   except subprocess.TimeoutExpired:
    child.terminate()
    try:child.wait(timeout=30)
    except subprocess.TimeoutExpired:child.kill();child.wait()
    raise TimeoutError('Terminated only our timed-out probe child')
  d=read_report(out/'report.json')
  if not d:raise RuntimeError('Probe produced no valid receipt')
  summary['reports'].append(compact(d,out/'report.json'));save()
  if rc!=0 or d['status']!='capacity_preflight_pass':
   summary['status']='stopped_after_rejected_candidate';summary['stop_reason']=d.get('error',d['status']);break
  previous=d
 else:summary['status']='completed'
 passed=[d for d in summary['reports'] if d['status']=='capacity_preflight_pass']
 summary['largest_tested_safe_batch']=max(d['batch'] for d in passed)
 best=max(passed,key=lambda d:d['rollout_decode_videos_per_minute'])
 # Within 3% of best throughput, prefer the smaller batch and larger memory margin.
 choices=[d for d in passed if d['rollout_decode_videos_per_minute']>=best['rollout_decode_videos_per_minute']*.97]
 summary['throughput_preferred_batch']=min(d['batch'] for d in choices)
 summary['formal_configuration_ready']=False
 summary['remaining_before_formal_run']=['actual HPSv3 reward contract integration','streamed384-video collection and two192-sample commit cadence','full runtime acceptance with preserved forward/replay geometry','user approval']
except Exception as e:
 summary.update(status='blocked_or_failed',error=type(e).__name__+': '+str(e),traceback=traceback.format_exc())
finally:
 summary['total_seconds']=time.monotonic()-started;summary.pop('child_pid',None);save();print(summary['status'],str(a.root/'suite-summary.json'),flush=True)
